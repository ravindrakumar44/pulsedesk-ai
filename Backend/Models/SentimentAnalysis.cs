using System.ComponentModel.DataAnnotations;

namespace HelpdeskSentiment.Api.Models;

public class SentimentAnalysis
{
    public int Id { get; set; }

    public int ComplaintId { get; set; }

    [Required]
    [MaxLength(30)]
    public string Sentiment { get; set; } = DomainConstants.Sentiments.Neutral;

    [Required]
    [MaxLength(40)]
    public string Emotion { get; set; } = DomainConstants.Emotions.Neutral;

    /// <summary>
    /// Normalized heuristic sentiment score in [-1.0, +1.0].
    /// Negative values indicate negative sentiment, positive values indicate positive sentiment.
    /// </summary>
    public double SentimentScore { get; set; }

    /// <summary>
    /// Calibrated probability score in [0.0, 1.0]. Remains null when generated by a
    /// heuristic lexicon analyzer rather than a calibrated probabilistic ML model.
    /// </summary>
    public double? ConfidenceScore { get; set; }

    [Required]
    public string Explanation { get; set; } = string.Empty;

    public DateTime AnalyzedAt { get; set; } = DateTime.UtcNow;

    public Complaint Complaint { get; set; } = null!;
}
